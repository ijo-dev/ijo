/**
 * Registry build. Reads every folder under src/components and produces:
 *
 *   src/generated/sources.ts  the real file text for the React / Vue / HTML tabs,
 *                             plus the gzipped size shown on each card.
 *   registry.json             a shadcn-compatible registry, which `shadcn build`
 *                             then turns into apps/web/public/r/<name>.json so
 *                             `npx shadcn add https://ijo.dev/r/<name>.json` works.
 *
 * Run it from the repo root with `pnpm registry`.
 */
import { gzipSync } from "node:zlib";
import { readFile, writeFile, readdir, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = resolve(here, "..");
const componentsDir = resolve(pkg, "src/components");

export const SITE_URL = process.env.IJO_SITE_URL ?? "https://ijo.dev";

/** Fails the build rather than shipping a half-filled card. */
const required = ["name", "title", "export", "category", "description", "behaviour", "added"];

const slugs = (await readdir(componentsDir, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

const items = [];
const generated = {};

for (const slug of slugs) {
  const dir = resolve(componentsDir, slug);
  const meta = JSON.parse(await readFile(resolve(dir, "meta.json"), "utf8"));

  for (const field of required) {
    if (!meta[field]) throw new Error(`${slug}/meta.json is missing "${field}"`);
  }
  if (meta.name !== slug) {
    throw new Error(`${slug}/meta.json says name "${meta.name}" — it must match the folder`);
  }

  const react = await readFile(resolve(dir, "component.tsx"), "utf8");
  const vue = await readFile(resolve(dir, "component.vue"), "utf8");
  const html = await readFile(resolve(dir, "component.html"), "utf8");

  // The budget in CLAUDE.md §5 is the shipped React source, GSAP excluded.
  const sizeGzip = gzipSync(Buffer.from(react, "utf8")).byteLength;
  const BUDGET = 3 * 1024;
  if (sizeGzip > BUDGET) {
    throw new Error(`${slug} is ${sizeGzip} B gzipped, over the ${BUDGET} B budget`);
  }

  generated[slug] = { sizeGzip, source: { react, vue, html } };

  items.push({
    name: slug,
    type: "registry:component",
    title: meta.title,
    description: meta.description,
    categories: [meta.category.toLowerCase()],
    dependencies: meta.dependencies ?? [],
    files: [
      {
        path: `src/components/${slug}/component.tsx`,
        type: "registry:component",
        target: `components/ijo/${slug}.tsx`,
      },
    ],
  });
}

const json = (value) => JSON.stringify(value, null, 2);

await mkdir(resolve(pkg, "src/generated"), { recursive: true });
await writeFile(
  resolve(pkg, "src/generated/sources.ts"),
  `/* Generated by packages/registry/scripts/build.mjs — do not edit. */
export const sources = ${json(generated)} as const;
`
);

await writeFile(
  resolve(pkg, "registry.json"),
  json({
    $schema: "https://ui.shadcn.com/schema/registry.json",
    name: "ijo",
    homepage: SITE_URL,
    items,
  }) + "\n"
);

console.log(`registry: ${items.length} component(s) → registry.json, src/generated/sources.ts`);
